export const adminDicts = { uk, ru };
export type AdminDict = typeof uk;

/** Язык панели из куки; по умолчанию украинский */
export async function getAdminLang(): Promise<AdminLang> {
  const value = (await cookies()).get(ADMIN_LANG_COOKIE)?.value;
  return value === "ru" ? "ru" : "uk";
}

export async function getAdminDict(): Promise<AdminDict> {
  return adminDicts[await getAdminLang()];
}
